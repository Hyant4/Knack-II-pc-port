"""Derive missing NID names from existing runtime export names, never from guesses."""
import argparse
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / 'port/scripts'))
from prepare import nid
from link_modules import module, canonical


def generate(game, names_file=None):
    source = ROOT / 'port/src'
    known = dict(re.findall(r'\{\s*"([^"]+)"\s*,\s*"([^"]+)"', (source / 'import_names.inc').read_text()))
    symbols = set()
    for path in source.glob('*.c'):
        symbols.update(re.findall(r'"([A-Za-z_][A-Za-z0-9_]+)"', path.read_text(encoding='utf-8')))
    symbols.update(known.values())
    if names_file:
        symbols.update(x.strip() for x in names_file.read_text(encoding='utf-8-sig').splitlines() if x.strip())
    by_nid = {nid(symbol): symbol for symbol in symbols}
    added = {}
    for file in [game / 'eboot.bin', game / 'game.elf', *(game / 'sce_module').glob('*.prx')]:
        for symbol in module(file)['symbols']:
            identity = symbol['identity']
            if symbol['section'] or not identity:
                continue
            key = canonical(identity)
            if key not in known and identity[0] in by_nid:
                added[key] = by_nid[identity[0]]
    text = '/* Generated by scripts/generate_knack_names.py from existing public runtime names. */\n'
    text += ''.join(f'{{"{key}", "{value}"}},\n' for key, value in sorted(added.items()))
    (source / 'knack_import_names.inc').write_text(text, encoding='utf-8')
    print(f'{len(added)} additional Knack import names verified by NID hash')


if __name__ == '__main__':
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('game', type=Path)
    p.add_argument('--names', type=Path, help='public ps4libdoc known_names.txt; matches are verified by hash')
    args = p.parse_args()
    generate(args.game, args.names)
