static inline const KnackAaSite* knack_aa_profile(const char* serial, const char* version) {
    if (!serial || !version) return NULL;
    /* USA 01.00 has the same allowlisted executable bytes as USA 01.01. */
    if (!strcmp(serial,"CUSA08014") && (!strcmp(version,"01.00") || !strcmp(version,"01.01")))
        return &knack_aa_us;
    if (!strcmp(serial,"CUSA07670") && !strcmp(version,"01.01")) return &knack_aa_eu;
    return NULL;
}
static inline int knack_aa_matches(const unsigned char* image, uint64_t size,
                                   const KnackAaSite* site) {
    if (!image || !site || site->instruction<16) return 0;
    const uint64_t start=site->instruction-16;
    return start<=size && sizeof(site->context)<=size-start &&
        !memcmp(image+start,site->context,sizeof(site->context));
}
static inline int knack_aa_apply(unsigned char* image, uint64_t size, const KnackAaSite* site) {
    /* vxorps xmm3,xmm3,xmm3 replaces vmulps xmm3,xmm1,xmm0; length and ABI unchanged.
     * The counter and all downstream projection/history consumers retain their native flow. */
    static const unsigned char zero_jitter[4]={0xc5,0xe0,0x57,0xdb};
    if (!knack_aa_matches(image,size,site)) return 0;
    memcpy(image+site->instruction,zero_jitter,sizeof(zero_jitter));
    return 1;
}
